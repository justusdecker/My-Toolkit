import base64
from tkinter.filedialog import askopenfilenames
from os.path import isfile
from ColorizeText import colorize_text
from pathlib import Path
from string import ascii_letters, digits
GC_ERROR_COLOR = '\033[31m'
GC_WARNING_COLOR = '\033[32m'
GC_ALL_OK_COLOR = '\033[34m'
GC_ALLOWED_FILETYPES = [('PNG Images','*.png'), ('JPEG Images', ('*.jpeg', '*.jpg'))]
GC_ALLOWED_FILEENDINGS = ['.png', 'jpg', 'jpeg']
GC_RESULT_PATH = './autogenerated_img_base64_results.py'
GC_AUTORESULT_MESSAGE = """
# Generated by CITB64Str - ©2025 - 2026 Justus Decker - licensed under MIT.
"""

def ConvertImages2B64(p_filepaths: tuple[str] | None, p_result_filepath: Path | None = None):
    """
    Converts Images from `png`, `jpeg` & `jpg` to Base64Bytes and write them summarized in a pythonfile.
    
    .. p_filepaths:: `tuple[str] | None` - If None a FileDialog from tkinter will open and the results from there are your filepaths, Shuts down early if nothing is selected!
    .. p_result_filepath:: The Path to the File you want to see the results in.
    """
    if p_result_filepath is None:
        l_result_filepath = GC_RESULT_PATH
    else:
        l_result_filepath = p_result_filepath
    l_result_base64_bytes_and_keys: dict[str, bytes] = {}
    l_file_counter = 0
    class ErrorsAndWarnings:
        m_errors = 0
        m_warnings = 0
    
    if p_filepaths is None:
        l_filepaths = askopenfilenames(filetypes=GC_ALLOWED_FILETYPES)
    else:
        l_filepaths = p_filepaths
    
    if not l_filepaths:
        print('No Files selected. Shut Down Application.')
        exit(1)
    
    def check_char_and_path_validity(p_path: Path) -> bool:
        """
        Checks in the filepath for illegal chars.
        """
        try:
            p_path.resolve()
            return True
        except OSError as OSE:
            print(check_char_and_path_validity(GC_ERROR_COLOR, f'[ERR] The Filename or path {p_path} is not valid or does not exist!'))
        
        return False
    
    def check_file_ending(p_path: Path) -> bool:
        """
        Checks in the filepath for the allowed fileendings.
        """
        l_result = str(p_path).endswith(GC_ALLOWED_FILEENDINGS)
        if not l_result: print(colorize_text(GC_ERROR_COLOR, f'[ERR] File: {p_path} must end with one of these options {GC_ALLOWED_FILEENDINGS}!'))
        return str(p_path).endswith(GC_ALLOWED_FILEENDINGS)
    
    def convert_filepath_to_python_conform_string(p_path: Path) -> str | bool:
        """
        Converts the filepath to:
        ```python
        result = 'GC_<p_path_checked_and_suffix_removed:str>_ICO'
        ```
        """
        l_filepath_as_string = str(p_path.name)
        for t_ending in GC_ALLOWED_FILEENDINGS:
            l_filepath_as_string = l_filepath_as_string.removesuffix(t_ending)
        
        if l_filepath_as_string[0] in digits:
            ErrorsAndWarnings.m_warnings += 1
            print(colorize_text(GC_WARNING_COLOR, ['[WAR] Variablenames should not be prefixed with a number']))
        
        if any([t_char not in ascii_letters + digits for t_char in l_filepath_as_string]):
            print(colorize_text(GC_ERROR_COLOR, ['[ERR] Variablenames should only contain ASCII-Letters & Digits']))
            return False
        
        return f'GC_{l_filepath_as_string.upper()}_ICO'
    
    def read_base64_bytes(p_path: Path) -> bytes | bool:
        """
        Reads a file and returns it as bytes - based on the given filepath.
        
        Returns: False on error
        
        Raises: On everything other than a OSError.
        """
        try:
            with open(p_path, 'rb') as f:
                return base64.b64encode(f.read()).decode('ascii')
        except OSError as OSE:
            print(colorize_text(GC_ERROR_COLOR, f'[ERR] File {p_path} - OSError'))
            ErrorsAndWarnings.m_errors += 1
            return False
        
    def write_results_to_file(p_path: Path, p_result: str) -> bool:
        try:
            with open(p_path,'w') as fo:
                fo.write(p_result)    
            return True
        except OSError as OSE:
            print(colorize_text(GC_ERROR_COLOR, f'[ERR] File {p_path} - OSError'))
            ErrorsAndWarnings.m_errors += 1
            return False    
        
    def combine_results_to_big_string(p_results: dict[str, bytes]) -> str:
        l_result_combined = GC_AUTORESULT_MESSAGE + '\n'
        for l_result in p_results:
            l_result_combined += f'{l_result} = {p_results[l_result]}\n'
        return l_result_combined
    
    for t_filepath in l_filepaths:
        l_file_counter += 1
        t_filepath_object = Path(t_filepath)
    
        if not check_char_and_path_validity(t_filepath_object):
            ErrorsAndWarnings.m_errors += 1
            continue
            
        if not check_file_ending(t_filepath_object):
            ErrorsAndWarnings.m_errors += 1
            continue
        
        t_string_variable_or_error = convert_filepath_to_python_conform_string(t_filepath_object)
        
        if t_string_variable_or_error is False:
            ErrorsAndWarnings.m_errors += 1
            continue
        
        if t_string_variable_or_error in l_result_base64_bytes_and_keys:
            print(colorize_text(GC_ERROR_COLOR, ['[ERR] Variablename is already in the results!']))
            ErrorsAndWarnings.m_errors += 1
            continue
    
        t_base64_encoded_bytes_or_error = read_base64_bytes(t_filepath_object)
        if t_base64_encoded_bytes_or_error is False:
            ErrorsAndWarnings.m_errors += 1
            continue
        else:
            l_result_base64_bytes_and_keys[t_string_variable_or_error] = t_base64_encoded_bytes_or_error
        
    l_result_string = combine_results_to_big_string(l_result_base64_bytes_and_keys)
    
    t_wrtf_has_error = write_results_to_file(l_result_filepath, l_result_string)
    if t_wrtf_has_error is False:
        ...
        
    if ErrorsAndWarnings.m_errors or ErrorsAndWarnings.m_warnings:
        print(colorize_text(GC_ERROR_COLOR,f'While generating [{ErrorsAndWarnings.m_errors} Errors, {ErrorsAndWarnings.m_warnings} Warnings]'))
    else:
        print(colorize_text(GC_ALL_OK_COLOR, 'No errors found.'))
    
    print(f'Finished Generating [{l_file_counter} Files]')
    
    if ErrorsAndWarnings.m_errors:
        exit(1)
    
if __name__ == '__main__':
    ConvertImages2B64(None, None)