"""
* Add Docstrings
"""
class Error: ...

import base64
from tkinter.filedialog import askopenfilenames
from pathlib import Path
from string import ascii_letters, digits, printable
from typing import Literal
from Log import log, LogTypes
GC_ALLOWED_CHARS = ascii_letters + digits + '_-'
GC_ALLOWED_FILETYPES = [('PNG Images','*.png'), ('JPEG Images', ('*.jpeg', '*.jpg'))]
GC_ALLOWED_FILEENDINGS = ['.png', 'jpg', 'jpeg']
GC_RESULT_PATH = './autogenerated_img_base64_results.py'
GC_AUTORESULT_MESSAGE = "# Generated by CITB64Str - ©2025 - 2026 Justus Decker - licensed under MIT.\n"

def ConvertImages2B64(p_filepaths: tuple[str] | None, p_result_filepath: Path | None = None):
    """
    Converts Images from `png`, `jpeg` & `jpg` to Base64Bytes and write them summarized in a pythonfile.
    
    * Early Exits on Critical Errors
    * Otherwise errors will be counted
    
    .. p_filepaths:: `tuple[str] | None` - If None a FileDialog from tkinter will open and the results from there are your filepaths, Shuts down early if nothing is selected!
    .. p_result_filepath:: The Path to the File you want to see the results in.
    """
    if p_result_filepath is None:
        l_result_filepath = GC_RESULT_PATH
    else:
        l_result_filepath = p_result_filepath
    l_result_base64_bytes_and_keys: dict[str, bytes] = {}
    l_file_counter = 0
    class ErrorsAndWarnings:
        m_errors = 0
        m_warnings = 0
    
    if p_filepaths is None:
        l_filepaths = askopenfilenames(filetypes=GC_ALLOWED_FILETYPES)
    else:
        l_filepaths = p_filepaths
    
    if not l_filepaths:
        log('No Files selected. Shut Down Application.', [], LogTypes.critical)
        exit(1)
    log('Files $: $',
        [len(l_filepaths), l_filepaths])
    
    def check_char_and_path_validity(p_path: Path) -> type[Error] | None:
        """
        Checks in the filepath for illegal chars.
        
        .. returns:: 
            `None` or 
            `Error`-Type on fail & increase errors by 1
        
        """
        try:
            p_path.resolve()
        except OSError as OSE:
            log(
                f'The Filename or path $ is not valid or does not exist!',
                [p_path],
                LogTypes.error
            )
            ErrorsAndWarnings.m_errors += 1
            return Error
    
    def check_file_ending(p_path: Path) -> type[Error] | bool:
        """
        Checks in the filepath for the allowed fileendings.
        
        .. returns:: 
            `bool` or 
            `Error`-Type on fail & increase errors by 1
        """
        l_result = str(p_path).endswith(tuple(GC_ALLOWED_FILEENDINGS))
        if not l_result: 
            log(
                f'File: $ must end with one of these options $!',
                [p_path, GC_ALLOWED_FILEENDINGS],
                LogTypes.error
            )
            ErrorsAndWarnings.m_errors += 1
            return Error
        return str(p_path).endswith(tuple(GC_ALLOWED_FILEENDINGS))
    
    def convert_filepath_to_python_conform_string(p_path: Path) -> type[Error] | str:
        """
        Converts the filepath to:
        ```python
        result = 'GC_<p_path_checked_and_suffix_removed:str>_ICO'
        
        Throws a warning if varname is prefixed with a digit
        
        .. returns:: 
            `str` or 
            `Error`-Type on fail & increase errors by 1
        ```
        """
        l_filepath_as_string = str(p_path.name)
        for t_ending in GC_ALLOWED_FILEENDINGS:
            l_filepath_as_string = l_filepath_as_string.removesuffix(t_ending)
        
        if l_filepath_as_string[0] in digits:
            ErrorsAndWarnings.m_warnings += 1
            log(
                f'Variablenames should $ prefixed with a number -> $',
                ['NEVER', l_filepath_as_string],
                LogTypes.warning
            )
        
        if any([t_char not in GC_ALLOWED_CHARS for t_char in l_filepath_as_string]):
            log(
                f'$ - Variablenames should only contain ASCII-Letters & Digits',
                [l_filepath_as_string],
                LogTypes.error
            )
            ErrorsAndWarnings.m_errors += 1
            return Error
        
        l_result = l_filepath_as_string.upper()
        l_contains_illegal = [c for c in l_result if c not in ascii_letters + digits]
        if l_contains_illegal:
            log(
                'Filename contains $ illegal characters: $ - The illegal chars will be removed but this can cause some problems like Double Naming',
                [len(l_contains_illegal), l_contains_illegal],
                LogTypes.warning
            )
            l_result = "".join([c for c in l_result if c in ascii_letters + digits])
        
        
        return f'GC_{l_result}_ICO'
    
    def read_base64_bytes(p_path: Path) -> str | type[Error]:
        """
        Reads a file and returns it as bytes - based on the given filepath.
        
        .. returns:: 
            `str` or 
            `Error`-Type on fail & increase errors by 1
        """
        try:
            with open(p_path, 'rb') as f:
                return base64.b64encode(f.read()).decode('ascii')
        except OSError as OSE:
            log(
                f'OSError for file read $',
                [p_path],
                LogTypes.error
            )
            ErrorsAndWarnings.m_errors += 1
            return Error
        
    def write_results_to_file(p_path: Path, p_result: str) -> type[Error] | None:
        """
        Writes the `p_result` to `p_path`
        
        .. returns:: 
            `None` or 
            `Error`-Type on fail & increase errors by 1
        """
        try:
            with open(p_path,'w', encoding='utf-8') as fo:
                fo.write(p_result)    
        except OSError as OSE:
            log(
                f'OSError for file write $',
                [p_path],
                LogTypes.error
            )
            ErrorsAndWarnings.m_errors += 1
            return Error   
        
    def combine_results_to_big_string(p_results: dict[str, bytes]) -> str:
        """
        Combines everything into human-readable content
        """
        l_result_combined = GC_AUTORESULT_MESSAGE + '\n'
        for l_result in p_results:
            l_result_combined += f'{l_result} = \"{p_results[l_result]}\"\n'
        return l_result_combined
    
    for t_filepath in l_filepaths:
        l_file_counter += 1
        t_filepath_object = Path(t_filepath)
    
        if check_char_and_path_validity(t_filepath_object) is Error: continue
            
        if check_file_ending(t_filepath_object) is Error: continue
        
        t_string_variable_or_error = convert_filepath_to_python_conform_string(t_filepath_object)
        
        if t_string_variable_or_error is Error: continue
        
        if t_string_variable_or_error in l_result_base64_bytes_and_keys:
            log(
                f'Variablename $ is already in the results!',
                [t_string_variable_or_error],
                LogTypes.error
            )
            ErrorsAndWarnings.m_errors += 1
            continue
    
        t_base64_encoded_bytes_or_error = read_base64_bytes(t_filepath_object)
        
        if t_base64_encoded_bytes_or_error is Error: continue
        else:
            l_result_base64_bytes_and_keys[t_string_variable_or_error] = t_base64_encoded_bytes_or_error
        
    l_result_string = combine_results_to_big_string(l_result_base64_bytes_and_keys)
    
    t_wrtf_has_error = write_results_to_file(l_result_filepath, l_result_string)
    if t_wrtf_has_error is Error:
        log(
            f'Cannot write results to $!',
            [l_result_filepath],
            LogTypes.critical
        )
        exit(1)
        
    if ErrorsAndWarnings.m_errors or ErrorsAndWarnings.m_warnings:
        log(
            f'While generating $ Errors & $ Warnings occured',
            [ErrorsAndWarnings.m_errors, ErrorsAndWarnings.m_warnings],
            LogTypes.error
        )
    else:
        log(
            f'While generating no errors occured',
            [],
            LogTypes.info
        )
    log(
        f'Finished Generating $ Files',
        [l_file_counter],
        LogTypes.info
    )
    
    if ErrorsAndWarnings.m_errors:
        exit(1)
    
if __name__ == '__main__':
    ConvertImages2B64(None, None)